// ============================================================================
// Build step: write js/env.js from environment variables.
//
// Runs on Vercel (via the "build" script in package.json). Reads the env vars
// set in the Vercel dashboard and bakes them into js/env.js, which the app
// imports. With no env vars set it reproduces the demo-mode default, so the
// build is safe to run anywhere (including locally).
//
// Only public, client-safe values belong here — Firebase web keys are public
// by design; the backend is protected by App Check + Firestore rules.
// ============================================================================

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, '..', 'js', 'env.js');

const env = (name, fallback = '') => {
  const v = process.env[name];
  return v == null || v === '' ? fallback : String(v);
};

const config = {
  FIREBASE_API_KEY: env('FIREBASE_API_KEY'),
  FIREBASE_AUTH_DOMAIN: env('FIREBASE_AUTH_DOMAIN'),
  FIREBASE_PROJECT_ID: env('FIREBASE_PROJECT_ID'),
  FIREBASE_APP_ID: env('FIREBASE_APP_ID'),
  APPCHECK_SITE_KEY: env('APPCHECK_SITE_KEY'),
  REPORT_EMAIL: env('REPORT_EMAIL', 'vikas070696@gmail.com'),
};

const banner = `// AUTO-GENERATED by scripts/apply-env-config.mjs at build time.
// Do not edit by hand — set values as environment variables in Vercel.
// Committed default (all blank) runs the site in demo mode.\n`;

writeFileSync(OUT, `${banner}\nexport const ENV = ${JSON.stringify(config, null, 2)};\n`);

const live = config.FIREBASE_API_KEY && config.FIREBASE_PROJECT_ID;
console.log(
  `[build] wrote js/env.js — mode: ${live ? 'LIVE (Firestore)' : 'demo'}, ` +
  `appCheck: ${config.APPCHECK_SITE_KEY ? 'on' : 'OFF'}`,
);
